def _obs(
    n: int,
    origin: str = "motor",
    *,
    topic: str | None = None,
    with_id: bool = True,
    signal: str | None = None,
    **extra,
) -> dict:
    entry = {
        "timestamp": f"2026-10-{1 + n % 28:02d}T{n % 24:02d}:00:{n % 60:02d}Z",
        "topic": topic or f"topic-{origin}-{n}",
        "signal": signal or f"REGLA {origin} {n}: " + "detalle " * 20,
        "source": "test",
        "_origin": origin,
        **extra,
    }
    if with_id:
        entry["id"] = f"obs-{origin}-{n}"
    return entry


def _bullets(index: str) -> list[str]:
    return [line for line in index.splitlines() if line.startswith("- ")]


