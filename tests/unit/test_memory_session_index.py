# --- CLI: --bootstrap acotado, --full entero, --recall llega mas alla -------


def _patch_memory(monkeypatch, corpus: list[dict]) -> None:
    monkeypatch.setattr(ml, "_read_portable_archive", lambda: list(corpus))
    monkeypatch.setattr(ml, "_try_read_file", lambda path: "")
    monkeypatch.setattr(ml, "_read_observations", lambda limit=0: [])
    monkeypatch.setattr(memory_context, "_anchor_memory_root", lambda: None)


def test_cli_bootstrap_is_bounded_and_carries_the_session_sections(monkeypatch, capsys):
    """`--bootstrap` = el MISMO arranque que el hook (ronda 4 #49): indice +
    pista + M4/M5, y <= SESSION_CONTEXT_MAX_CHARS.
    """
    corpus = [_obs(i) for i in range(400)]
    _patch_memory(monkeypatch, corpus)
    monkeypatch.setattr("sys.argv", ["memory_context.py", "--bootstrap"])

    rc = memory_context.main()
    out = capsys.readouterr().out

    assert rc == 0
    assert len(out.rstrip("\n")) <= ml.SESSION_CONTEXT_MAX_CHARS
    assert ml.MEMORY_INDEX_OPEN in out
    assert "Memoria: cuando expandir" in out
    assert "M4/M5" in out


def test_cli_full_is_wrapped_and_unbounded(monkeypatch, capsys):
    """Ronda 4 #46: `--full` lleva el mismo envoltorio (un backend que lo
    ejecuto no debe recargar con `--bootstrap`) y no aplica el presupuesto.
    """
    corpus = [_obs(i) for i in range(400)]
    _patch_memory(monkeypatch, corpus)
    monkeypatch.setattr("sys.argv", ["memory_context.py", "--full"])

    rc = memory_context.main()
    out = capsys.readouterr().out

    assert rc == 0
    assert out.startswith(ml.MEMORY_INDEX_OPEN)
    assert out.rstrip().endswith(ml.MEMORY_INDEX_CLOSE)
    assert len(out) > ml.SESSION_CONTEXT_MAX_CHARS


def test_recall_reaches_a_lesson_the_index_omits(monkeypatch, capsys):
    """Lo que el indice omite sigue siendo alcanzable por `--recall --id`."""
    corpus = [_obs(i) for i in range(400)]
    index = ml.format_memory_index(corpus)
    omitted = next(o for o in corpus if f"{o['id']}:" not in index)
    _patch_memory(monkeypatch, corpus)
    monkeypatch.setattr(ml, "is_lesson", lambda obs: True)
    monkeypatch.setattr(
        "sys.argv", ["memory_context.py", "--recall", "--id", omitted["id"]]
    )

    rc = memory_context.main()
    out = capsys.readouterr().out

    assert rc == 0
    assert omitted["signal"].split(":")[0] in out


def test_print_recall_keeps_later_entries_that_still_fit(capsys):
    """`_print_recall`: una entrada demasiado grande ya no arrastra a las
    siguientes que si caben (antes: `if omitted or ...`).
    """
    small_a = {"topic": "a", "signal": "A" * 50, "source": "s"}
    huge = {"topic": "huge", "signal": "H" * 5_000, "source": "s"}
    small_b = {"topic": "b", "signal": "B" * 50, "source": "s"}

    memory_context._print_recall([small_a, huge, small_b], budget=400)
    out = capsys.readouterr().out

    assert "A" * 50 in out and "B" * 50 in out
    assert "1 entrada(s) omitida(s)" in out
