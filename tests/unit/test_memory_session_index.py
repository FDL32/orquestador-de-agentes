ROOT = Path(__file__).resolve().parents[2]


def _obs(
    n: int,
    origin: str = "motor",
    *,
    topic: str | None = None,
    with_id: bool = True,
    signal: str | None = None,
    **extra,
) -> dict:
    entry = {
        "timestamp": f"2026-10-{1 + n % 28:02d}T{n % 24:02d}:00:{n % 60:02d}Z",
        "topic": topic or f"topic-{origin}-{n}",
        "signal": signal or f"REGLA {origin} {n}: " + "detalle " * 20,
        "source": "test",
        "_origin": origin,
        **extra,
    }
    if with_id:
        entry["id"] = f"obs-{origin}-{n}"
    return entry


def _bullets(index: str) -> list[str]:
    return [line for line in index.splitlines() if line.startswith("- ")]


# --- format_memory_index: bordes ------------------------------------------


def test_empty_corpus_yields_empty_string():
    """Corpus vacio -> "" (el llamante lo distingue de un fallo de carga)."""
    assert ml.format_memory_index([], local_text="") == ""


@pytest.mark.parametrize("size", [1, 10, 400])
def test_single_origin_respects_budget_and_floor(size):
    """Un origen: nunca pasa el presupuesto y llega al suelo min(25, disponibles).

    MUTACION ALCANZABLE: quitar la busqueda del N mayor que cabe (fijar N=5)
    -> el suelo cae con 400 entradas.
    """
    corpus = [_obs(i) for i in range(size)]
    index = ml.format_memory_index(corpus)
    assert len(index) <= ml.INDEX_BUDGET_CHARS
    assert index.startswith(ml.MEMORY_INDEX_OPEN)
    assert index.endswith(ml.MEMORY_INDEX_CLOSE)
    assert len(_bullets(index)) >= min(ml.INDEX_FLOOR_TOTAL, size)


def test_two_origins_each_keep_their_floor():
    """Dos origenes: cada uno conserva min(10, disponibles) aunque el otro sea
    mas reciente y mucho mayor (la cuota por origen sobrevive al presupuesto).
    """
    motor = [_obs(i, "motor") for i in range(300)]
    destino = [_obs(i, "local", signal=f"DESTINO {i} " + "x " * 20) for i in range(4)]
    for entry in destino:
        entry["timestamp"] = "2026-01-01T00:00:00Z"  # mas antiguas que el motor
    index = ml.format_memory_index(motor + destino)
    bullets = _bullets(index)
    assert len(index) <= ml.INDEX_BUDGET_CHARS
    assert sum("obs-local-" in b for b in bullets) == min(
        ml.INDEX_FLOOR_PER_ORIGIN, len(destino)
    )
    assert sum("obs-motor-" in b for b in bullets) >= ml.INDEX_FLOOR_PER_ORIGIN


def test_large_local_tier_is_subcapped_and_never_starves_the_index():
    """Un tier local enorme se recorta a su sub-tope; el indice conserva su suelo."""
    corpus = [_obs(i) for i in range(200)]
    index = ml.format_memory_index(corpus, local_text="L2 regla\n" * 5_000)
    assert len(index) <= ml.INDEX_BUDGET_CHARS
    assert "## Tier local" in index
    assert len(_bullets(index)) >= ml.INDEX_FLOOR_TOTAL


def test_tiny_budget_never_returns_an_open_wrapper():
    """Presupuesto menor que cabecera+pie: bloque cerrado o vacio, nunca abierto."""
    index = ml.format_memory_index([_obs(i) for i in range(50)], budget=120)
    assert len(index) <= 120
    assert index == "" or index.endswith(ml.MEMORY_INDEX_CLOSE)


