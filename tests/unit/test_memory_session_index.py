"""Diseno v6 (2026-10-23): indice de memoria ACOTADO para cualquier arranque.

Contexto medido. El hook SessionStart inyectaba ~33.6k chars (startup) y ~29.1k
(resume/compact), por encima del tope de 10.000 de `additionalContext` de
Claude Code, y los backends sin hook (Codex, Kilo, OpenCode) ejecutaban otro
comando, sin tope. `format_memory_index` es el MISMO artefacto para todos:
acotado, deduplicado, con carril estable y reciente, y con un pie que declara
lo omitido y como expandirlo.

Cubre los cambios de la ronda 4 (#43, #46, #52-#54, #60, #63) y el arreglo de
`_print_recall` (una omision ya no arrastra a las entradas que si caben).
"""

from __future__ import annotations

