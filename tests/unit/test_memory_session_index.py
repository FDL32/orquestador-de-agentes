def test_duplicates_are_shown_and_counted_once():
    """Ronda 4 #53: 483 filas / 398 `dedup_key`. Una repeticion no gasta plaza."""
    entry = _obs(1, memory_class="contrato-operativo")
    older = {**entry, "timestamp": "2026-01-01T00:00:00Z"}
    index = ml.format_memory_index([entry, older, _obs(2)])
    assert sum("obs-motor-1:" in b for b in _bullets(index)) == 1
    assert "2 leccion(es) vigentes" in index


def test_stable_lane_is_capped_and_one_per_topic():
    """Ronda 4 #55: carril estable <= 5, una entrada por topic."""
    stable = [
        _obs(i, topic=f"t{i % 3}", memory_class="contrato-operativo") for i in range(12)
    ]
    index = ml.format_memory_index(stable + [_obs(100 + i) for i in range(40)])
    section = index.split("## Estables")[1].split("## Recientes")[0]
    lane = [line for line in section.splitlines() if line.startswith("- ")]
    assert len(lane) == 3  # 3 topics distintos, tope 5
    assert len(lane) <= ml._STABLE_LANE_CAP


def test_stable_entries_are_not_repeated_in_the_recent_lane():
    """Ronda 4 (sonnet #7): una estable no reaparece en el carril reciente."""
    stable = _obs(1, memory_class="arquitectura-estable")
    index = ml.format_memory_index([stable] + [_obs(i) for i in range(2, 30)])
    assert sum("obs-motor-1:" in b for b in _bullets(index)) == 1


def test_refuted_entries_never_take_a_vigent_slot():
    refuted = _obs(1, status="refuted", refuted_by="obs-motor-2")
    index = ml.format_memory_index([refuted, _obs(2)])
    assert "[REFUTADA]" in index
    assert "1 leccion(es) vigentes" in index


def test_footer_declares_omissions_with_and_without_id_and_the_full_door():
    """Ronda 4 #47/#52: el pie cuenta lo omitido (con y sin id) y da `--full`."""
    corpus = [_obs(i) for i in range(200)] + [
        _obs(500 + i, with_id=False) for i in range(50)
    ]
    index = ml.format_memory_index(corpus)
    shown = len(_bullets(index))
    assert "con id" in index and "sin id" in index
    assert "--full" in index and "--recall" in index
    assert shown < 250  # algo se omitio, y se declara


def test_line_without_id_carries_its_own_recall_query():
    index = ml.format_memory_index([_obs(1, with_id=False, topic="sin-id-topic")])
    assert "- sin-id-topic:" in index
    assert "(--recall --query sin-id-topic)" in index


def test_signal_is_cut_at_a_word_boundary():
    long_signal = "palabra " * 40
    index = ml.format_memory_index([_obs(1, signal=long_signal)])
    line = next(b for b in _bullets(index) if "obs-motor-1" in b)
    assert line.endswith("...")
    assert "palabr..." not in line


# --- _cap_preserving_origins: orden y filtro en TODA salida (#54) -----------


@pytest.mark.parametrize("cap", [5, 20, 60, 500])
def test_cap_preserving_origins_is_newest_first_at_every_cap(cap):
    """Ronda 4 #54: las ramas `len <= cap` devolvian la entrada SIN ordenar
    (agrupada por origen). Con dos origenes la salida debe ser newest-first
    para cualquier cap, incluido cap >= len.

    MUTACION ALCANZABLE: restaurar `if len(observations) <= cap: return
    observations` -> cae para cap=500.
    """
    corpus = [_obs(i, "motor") for i in range(30)] + [
        _obs(i, "local") for i in range(30, 45)
    ]
    out = ml._cap_preserving_origins(corpus, cap)
    stamps = [o["timestamp"] for o in out]
    assert stamps == sorted(stamps, reverse=True)
    assert len(out) == min(cap, len(corpus))


def test_cap_preserving_origins_drops_templates_even_under_the_cap():
    """Las plantillas autogeneradas no entran ni cuando todo cabe (monotonia)."""
    lessons = [_obs(i) for i in range(3)]
    template = _obs(9, topic=sorted(AUTOGENERATED_TOPICS)[0])
    out = ml._cap_preserving_origins([*lessons, template], 500)
    assert template not in out
    assert len(out) == 3


