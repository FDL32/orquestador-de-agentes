def test_f_dedup_por_clave_antecede_al_filtro_lesson() -> None:
    """El dedup por clave se ejecuta DESPUES del filtro is_lesson.

    Una entrada duplicada por clave con signal < 60 (o topic de plantilla)
    NO expulsa a la version antigua VALIDA.

    Fixture sintetico: 2 entradas con el mismo id; la MAS NUEVA tiene
    signal < 60 chars; la ANTIGUA es una leccion valida (signal >= 60,
    topic=testing). La antigua SI debe entrar (1 regla, 1 candidata).

    Debe ir ROJO si se mantiene el orden de la ronda 1 (dedup antes del
    filtro): la nueva invalida expulsa a la antigua valida.
    """
    nueva_invalida = {
        "id": "obs-dedup-f",
        "signal": "Señal nueva corta que no pasa el filtro de longitud.",
        "topic": "ticket-completion",
        "source_ticket": "WOT-2026-900a",
        "timestamp": "2026-10-24T10:00:00+00:00",
    }
    antigua_valida = {
        "id": "obs-dedup-f",  # MISMO id
        "signal": "Regla antigua validada con signal de mas de "
        "cien caracteres que supera con creces el umbral minimo de "
        "sesenta caracteres exigido por la prueba.",
        "topic": "testing",
        "source_ticket": "WOT-2026-800a",
        "timestamp": "2026-10-20T10:00:00+00:00",
    }

    result = _extract_rules_from_entries([antigua_valida, nueva_invalida])
    assert len(result["rules"]) == 1, (
        "la entrada antigua valida debe entrar aunque la nueva sea invalida"
    )
    assert result["candidates"] == 1, (
        "solo la antigua valida debe contar como candidata"
    )
    assert result["rules"][0]["signal"] == antigua_valida["signal"]


