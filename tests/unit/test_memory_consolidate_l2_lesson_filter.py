# Test (d): pasa por _regenerate_l2_l3 (o reproduce local + archived)
# =============================================================================


def test_d_pasa_por_regenerate_l2_l3_no_por_lista_sucia(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """El dedup por clave opera sobre la UNION de `recent` + `archivable`
    que forma `local` dentro de `_regenerate_l2_l3`.

    Una entrada mas antigua en `archivable` y una mas reciente con el mismo
    `id` pero `signal` distinto: L2 queda con 1 regla (la mas reciente).
    Debe ir ROJO si se quita el bucle de dedup por clave.

    Las DOS entradas de mismo `id` y `signal` distinto estan repartidas en
    `recent` (una) y `archivable` (otra), que es como llegan en produccion.
    L1/L2/L3 se redirigen a `tmp_path` via `monkeypatch`.
    """
    import scripts.memory_consolidate as mc

    old_ts = "2026-10-20T10:00:00+00:00"
    new_ts = "2026-10-24T10:00:00+00:00"

    archivable_entry = {
        "id": "obs-same-dedup-id",
        "signal": "Signal viejo con texto distinto al nuevo, pero "
        "ambos superan el umbral de sesenta caracteres "
        "necesario para pasar el filtro de longitud de signal.",
        "topic": "testing",
        "source_ticket": "WOT-2026-700a",
        "timestamp": old_ts,
    }
    recent_entry = {
        "id": "obs-same-dedup-id",  # MISMO id, signal distinto
        "signal": "Signal nuevo con texto diferente al viejo, pero "
        "ambos superan el umbral de sesenta caracteres "
        "necesario para pasar el filtro de longitud de signal.",
        "topic": "testing",
        "source_ticket": "WOT-2026-800a",
        "timestamp": new_ts,
    }

    rules_path = tmp_path / "memory_rules.md"
    profile_path = tmp_path / "memory_profile.md"
    monkeypatch.setattr(mc, "MEMORY_RULES_MD", rules_path)
    monkeypatch.setattr(mc, "MEMORY_PROFILE_MD", profile_path)

    mc._regenerate_l2_l3(
        recent=[recent_entry], verbose=False, archivable=[archivable_entry]
    )

    rules_txt = rules_path.read_text(encoding="utf-8")
    assert "Total rules: 1" in rules_txt, (
        "dos entradas con el mismo id deben colapsar a 1 regla, no 2"
    )
    assert recent_entry["signal"] in rules_txt, (
        "la entrada mas reciente debe sobrevivir al dedup por clave en L2"
    )
    assert archivable_entry["signal"] not in rules_txt, (
        "la entrada antigua con el mismo id no debe aparecer"
    )


