# =============================================================================
# Test (b): dos filas con mismo id y signal distinto -> 1 slot, gana mas reciente
# =============================================================================


def test_b_mismo_id_diferente_signal_gana_reciente() -> None:
    """Dos filas con el mismo `id` y `signal` DISTINTO ocupan UN slot y
    gana la mas reciente.

    Fixture sintetico: dos entradas con id=obs-same-id, signals distintos
    (>= 60 chars), topics validos (no template), timestamps distintos.
    """
    now = datetime(2026, 10, 24, 10, 0, 0, tzinfo=timezone.utc)
    old = (now - timedelta(days=5)).isoformat()
    new_ts = now.isoformat()

    old_entry = {
        "id": "obs-same-id",
        "signal": "Regla antigua sobre testing A. con texto suficientemente "
        "largo para pasar el filtro de longitud minima.",
        "topic": "testing",
        "source_ticket": "WOT-2026-100a",
        "timestamp": old,
    }
    new_entry = {
        "id": "obs-same-id",
        "signal": "Regla nueva sobre testing B. con texto suficientemente "
        "largo para pasar el filtro de longitud minima y ganar el slot.",
        "topic": "testing",
        "source_ticket": "WOT-2026-200a",
        "timestamp": new_ts,
    }

    result = _extract_rules_from_entries([old_entry, new_entry])
    assert len(result["rules"]) == 1, (
        "dos entradas con el mismo id deben ocupar 1 slot, no 2"
    )
    assert result["candidates"] == 1
    assert result["rules"][0]["signal"] == new_entry["signal"], (
        "la entrada mas reciente debe sobrevivir al dedup por clave"
    )


