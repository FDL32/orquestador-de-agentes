# Test (e): snapshot -- pool crece, altas y bajas exactas
# =============================================================================


def test_e_snapshot_pool_crece_con_124c(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Snapshot: sobre un fixture fijo pequeno, la lista de slots antes/despues
    del cambio con las altas y bajas EXACTAS esperadas (efecto colateral: el
    pool crece).

    El fixture tiene 8 entradas:
    - 2 plantilla (topic=ticket-completion, en AUTOGENERATED_TOPICS) -> NO
      entran ni antes ni despues de 124c.
    - 2 con domain y keywords inglesas (must be, this) -> entran siempre.
    - 2 leccion espanol sin domain ni keywords (>=60 chars) -> NO entraban
      antes (rule_likeness=0, has_domain=False), SI entran con is_lesson.
    - 2 leccion espanol con domain pero sin keywords -> NO entraban antes
      (rule_likeness=0, has_domain si), SI entran con is_lesson.

    Antes (filtro viejo): 4 rules (2 domain+keywords + 2 con has_domain
    pero sin keywords). Espera: has_domain=True las dejaba pasar siempre, asi
    que las 6 no-plantilla entraban. Despues (filtro nuevo): 6 rules (todas las
    6 no-plantilla porque is_lesson=True y signal >= 60).

    El efecto neto de 124c: las plantillas ya no entraban (por length o por
    has_domain=0), asi que la ganancia real es las 2 espanol sin domain que
    ahora entran via is_lesson.

    MUTACION: volver al filtro viejo (rule_likeness + has_domain) -> el test
    cae porque las lecciones espanol sin keywords no entran.
    """
    now = datetime.now(timezone.utc).isoformat()

    entries = [
        # Plantilla (topic=ticket-completion en AUTOGENERATED_TOPICS)
        # -> is_lesson=False, no entran nunca.
        {
            "signal": "Ticket completado: Unknown -- la sesion marco la tarea "
            "como completada sin verificar el DoD, y nadie lo cazo hasta hoy.",
            "topic": "ticket-completion",
            "id": "obs-tpl-1",
            "timestamp": now,
        },
        {
            "signal": "Otra linea de telemetria generada automaticamente por "
            "el sistema de cierre de sesion con un topic template estandar.",
            "topic": "ticket-completion",
            "id": "obs-tpl-2",
            "timestamp": now,
        },
        # Con domain + keyword inglesa -> entran siempre.
        {
            "signal": "Rule R1: Always verify the dependency before merging; "
            "this must be re-measured with a command.",
            "topic": "testing",
            "domain": "dep-verify",
            "source_ticket": "WOT-2026-100a",
            "timestamp": now,
        },
        {
            "signal": "Rule R2: Always check the config before deploy; "
            "this must be re-measured with a command.",
            "topic": "testing",
            "domain": "config-check",
            "source_ticket": "WOT-2026-200a",
            "timestamp": now,
        },
        # Espanol sin domain ni keywords -> NO entraban antes, SI despues.
        {
            "signal": "La auditoria de dependencias debe usar pip-audit sobre el "
            "entorno virtual del proyecto, nunca sobre el sistema global del host.",
            "topic": "security-audit",
            "source_ticket": "WOT-2026-300a",
            "timestamp": now,
        },
        {
            "signal": "El cierre de sesion debe verificar que el arbol esta "
            "limpio antes de commitear el reporte de consolidacion final.",
            "topic": "closeout",
            "source_ticket": "WOT-2026-400a",
            "timestamp": now,
        },
        # Espanol con domain pero sin keywords -> entraban por has_domain
        # (viejo), siguen entrando por is_lesson (nuevo).
        {
            "signal": "La memoria persistente se consolida al cierre de sesion "
            "con el script memory_consolidate.py, que deduplica y archivia.",
            "topic": "memory",
            "domain": "memory-persist",
            "source_ticket": "WOT-2026-500a",
            "timestamp": now,
        },
        {
            "signal": "El gestor de tickets usa un backlog vivo para gestionar "
            "las solicitudes pendientes del equipo de desarrollo activo.",
            "topic": "project-mgmt",
            "domain": "ticket-backlog",
            "source_ticket": "WOT-2026-600a",
            "timestamp": now,
        },
    ]

    # Verificamos que las entradas 'espanol' son lecciones (is_lesson=True).
    from bus.portable_memory_archive import is_lesson

    for i in range(4, 8):
        assert is_lesson(entries[i]), (
            f"entry {i} debe ser leccion para que el snapshot funcione"
        )
    # Y las plantillas NO son lecciones.
    for i in range(2):
        assert not is_lesson(entries[i]), (
            f"entry {i} debe ser template para filtrarse por is_lesson"
        )

    result = _extract_rules_from_entries(entries)
    assert result["candidates"] == 6, (
        f"se esperan 6 candidatas (2 plantilla filtradas por is_lesson); "
        f"got {result['candidates']}"
    )
    assert len(result["rules"]) == 6, (
        f"se esperan 6 reglas tras aplicar is_lesson; got {len(result['rules'])}"
    )
    assert result["truncated"] is False

    # Verificamos que las reglas son las esperadas.
    rule_signals = {r["signal"] for r in result["rules"]}
    # Las 2 siempre entraban.
    assert any("Rule R1" in s for s in rule_signals)
    assert any("Rule R2" in s for s in rule_signals)
    # Las 2 espanol sin domain ni keywords (ganancia de 124c).
    assert any("pip-audit" in s for s in rule_signals)
    assert any("cierre de sesion" in s for s in rule_signals)
    # Las 2 espanol con domain (siempre entraban por has_domain, siguen).
    assert any("memory_consolidate" in s for s in rule_signals)
    assert any("backlog" in s for s in rule_signals)
    # Ninguna plantilla.
    assert not any("completado: Unknown" in s for s in rule_signals)


