# Test (b2): fila sin id cuyo generate_stable_id coincide con id de otra
# =============================================================================


def test_b2_sin_id_con_stable_id_coincide_con_id_de_otra() -> None:
    """Una fila sin `id` cuyo `generate_stable_id` coincide con el `id` de
    otra fila de `local` ocupa el mismo slot que esa.

    Fixture sintetico: una entrada sin id cuyo redact content genera el mismo
    stable_id que el id explicito de otra entrada con id.
    """
    # Entrada sin id. Su redact content dara un stable_id especifico.
    no_id_entry = {
        "signal": "Leccion sin id pero con enough texto suficiente para pasar "
        "el filtro de longitud y ser validada correctamente en el test.",
        "topic": "testing",
        "source_ticket": "WOT-2026-300a",
        "timestamp": "2026-10-23T10:00:00+00:00",
    }
    redacted = _redact_entry(no_id_entry)
    stable_id = generate_stable_id(redacted)

    # Segunda entrada CON id que coincide con el stable_id de la primera.
    with_id_entry = {
        "id": stable_id,
        "signal": "Leccion con id explicito y con enough texto suficiente para "
        "pasar el filtro de longitud y competir por el mismo slot.",
        "topic": "testing",
        "source_ticket": "WOT-2026-400a",
        "timestamp": "2026-10-24T10:00:00+00:00",
    }

    result = _extract_rules_from_entries([no_id_entry, with_id_entry])
    assert len(result["rules"]) == 1, (
        "dos entradas colisionadas por stable_id deben ocupar 1 slot"
    )
    assert result["candidates"] == 1


