#!/usr/bin/env python3
"""Migration script for portable memory archive observations schema (WOT-2026-214a).

Normalizes missing 'id' fields in portable memory archive files
('observations.YYYY-MM.jsonl') using deterministic stable ids generated by
bus.portable_memory_archive.generate_stable_id.

Invariants:
  1. Runtime buffer 'observations.jsonl' is STRICTLY READ-ONLY and will be refused.
  2. Idempotent: a second run produces 0 byte diff and identical sha256.
  3. Pre- and post-validation: files must satisfy validate_observations.py --strict.
  4. Dry-run by default; --apply required to write changes to disk.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any


# Bootstrap repo_motor root
_MOTOR_ROOT = Path(__file__).resolve().parent.parent
if str(_MOTOR_ROOT) not in sys.path:
    sys.path.insert(0, str(_MOTOR_ROOT))

from bus.portable_memory_archive import (  # noqa: E402
    ARCHIVE_DIR_REL,
    ARCHIVE_GLOB,
    generate_stable_id,
)


def _validate_with_strict(archive_file: Path) -> tuple[bool, str]:
    """Run validate_observations.py --strict on target file (fail-closed)."""
    validator_script = _MOTOR_ROOT / "scripts" / "validate_observations.py"
    if not validator_script.exists():
        return False, f"Validator script missing: {validator_script}"
    res = subprocess.run(  # noqa: S603
        [
            sys.executable,
            str(validator_script),
            "--strict",
            "--file",
            str(archive_file),
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    return res.returncode == 0, res.stderr or res.stdout


def migrate_record(record: dict[str, Any]) -> tuple[dict[str, Any], bool]:
    """Ensure record has a stable 'id' field.

    Returns (normalized_record, was_changed).
    """
    existing_id = record.get("id")
    if isinstance(existing_id, str) and existing_id.strip():
        return record, False

    new_id = generate_stable_id(record)
    new_record: dict[str, Any] = {
        "id": new_id,
        **{k: v for k, v in record.items() if k != "id"},
    }
    return new_record, True


def _parse_and_migrate_lines(
    raw_lines: list[str],
    file_path: Path,
) -> tuple[list[str], int, int]:
    """Parse JSON lines and return migrated lines and counts."""
    new_lines: list[str] = []
    migrated_count = 0
    unchanged_count = 0

    for line_idx, line in enumerate(raw_lines, 1):
        stripped = line.strip()
        if not stripped:
            continue
        try:
            record = json.loads(stripped)
        except json.JSONDecodeError as exc:
            raise ValueError(f"{file_path}:{line_idx}: invalid JSON ({exc})") from exc

        if not isinstance(record, dict):
            unchanged_count += 1
            new_lines.append(stripped)
            continue

        updated_record, was_changed = migrate_record(record)
        if was_changed:
            migrated_count += 1
            new_lines.append(json.dumps(updated_record, ensure_ascii=False))
        else:
            unchanged_count += 1
            # Preserve original text for unchanged lines to preserve exact byte formatting
            new_lines.append(stripped)

    return new_lines, migrated_count, unchanged_count


def _atomic_write_archive(file_path: Path, new_lines: list[str]) -> None:
    """Safely write new_lines to file_path with pre-validation and rollback."""
    parent_dir = file_path.parent
    fd, tmp_path_str = tempfile.mkstemp(
        prefix="obs_mig_",
        suffix=".tmp",
        dir=parent_dir,
    )
    tmp_path = Path(tmp_path_str)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            for nl in new_lines:
                fh.write(nl + "\n")

        valid, err_msg = _validate_with_strict(tmp_path)
        if not valid:
            raise RuntimeError(
                f"Post-migration validation failed for {file_path}: {err_msg}"
            )

        os.replace(tmp_path, file_path)
    except Exception:
        if tmp_path.exists():
            tmp_path.unlink()
        raise


def migrate_archive_file(
    file_path: Path,
    *,
    apply: bool = False,
) -> tuple[int, int]:
    """Migrate missing ids in a single archive file.

    Returns (migrated_count, unchanged_count).
    Raises ValueError if targeting runtime observations.jsonl.
    """
    resolved = file_path.resolve()
    if resolved.name == "observations.jsonl":
        raise ValueError(
            f"observations.jsonl ({file_path}) is runtime buffer and read-only; "
            "migration is only allowed on portable archive files."
        )

    if not file_path.exists():
        return 0, 0

    if apply:
        pre_valid, pre_err = _validate_with_strict(file_path)
        if not pre_valid:
            raise RuntimeError(
                f"Pre-migration validation failed for {file_path}: {pre_err}"
            )

    content = file_path.read_text(encoding="utf-8")
    raw_lines = content.splitlines()

    new_lines, migrated_count, unchanged_count = _parse_and_migrate_lines(
        raw_lines, file_path
    )

    if apply and migrated_count > 0:
        _atomic_write_archive(file_path, new_lines)

    return migrated_count, unchanged_count


def migrate_archive_dir(
    archive_dir: Path,
    *,
    apply: bool = False,
) -> dict[str, tuple[int, int]]:
    """Migrate all archive files in archive_dir.

    Returns dict mapping filename to (migrated_count, unchanged_count).
    """
    results: dict[str, tuple[int, int]] = {}
    if not archive_dir.is_dir():
        return results

    for path in sorted(archive_dir.glob(ARCHIVE_GLOB)):
        migrated, unchanged = migrate_archive_file(path, apply=apply)
        results[path.name] = (migrated, unchanged)
    return results


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Migrate portable memory archive schema to include stable ids (WOT-2026-214a)."
    )
    group = parser.add_mutually_exclusive_group()
    group.add_argument(
        "--file",
        type=Path,
        default=None,
        help="Path to single archive file to migrate.",
    )
    group.add_argument(
        "--archive-dir",
        type=Path,
        default=None,
        help="Path to directory containing archive files.",
    )
    parser.add_argument(
        "--apply",
        action="store_true",
        help="Apply changes to disk (default: dry-run).",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Report changes without writing to disk.",
    )

    args = parser.parse_args()
    apply = args.apply and not args.dry_run

    if args.file:
        try:
            migrated, unchanged = migrate_archive_file(args.file, apply=apply)
            mode_str = "[APPLIED]" if apply else "[DRY-RUN]"
            print(f"{mode_str} {args.file}: migrated={migrated}, unchanged={unchanged}")
            return 0
        except Exception as exc:
            print(f"ERROR: {exc}", file=sys.stderr)
            return 1

    target_dir = args.archive_dir or (_MOTOR_ROOT / ARCHIVE_DIR_REL)
    if not target_dir.is_dir():
        print(f"Directory not found: {target_dir}", file=sys.stderr)
        return 1

    results = migrate_archive_dir(target_dir, apply=apply)
    total_migrated = sum(m for m, _ in results.values())
    total_unchanged = sum(u for _, u in results.values())
    mode_str = "[APPLIED]" if apply else "[DRY-RUN]"

    for fname, (m, u) in results.items():
        print(f"  {fname}: migrated={m}, unchanged={u}")

    print(f"{mode_str} Total: migrated={total_migrated}, unchanged={total_unchanged}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
